export function findCatalogItem(item) {
  if (!item || typeof item !== 'object') return null;

  const keyCandidate = String(item.bookId || item.id || item.slug || '')
    .trim()
    .toLowerCase();
  if (keyCandidate && CATALOG_ITEMS[keyCandidate]) {
    return { key: keyCandidate, ...CATALOG_ITEMS[keyCandidate] };
  }

  const nameCandidate = String(item.name || '').trim().toLowerCase();
  for (const [key, value] of Object.entries(CATALOG_ITEMS)) {
    if (
      nameCandidate === key ||
      nameCandidate === value.en?.toLowerCase() ||
      nameCandidate === value.kn?.toLowerCase()
    ) {
      return { key, ...value };
    }
  }

  return null;
}
